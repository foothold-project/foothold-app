#!/usr/bin/env python3
"""Generate include/foothold/moves_dog_sit.hpp from factory-mode traces of the real Go2 X.

Each row holds q, dq and tau (measured motor torque) at 50 Hz, policy joint order
(hip FL FR RL RR, thigh FL FR RL RR, calf FL FR RL RR). The runner replays q and dq and
feeds a scaled tau forward, so the factory's own effort (weight shift, foot lift) comes back.

Sources (foothold-recorder factory-auto traces, wall time in KST):
  dog sit   11/26 06:27:27.26 R1+B   factory-auto-20261126-062117-000.jsonl
            taps  press + 0.00 .. 0.46 s (FL+RR then FR+RL; only tau is used)
            sit   press + 0.46 .. 1.40 s
  dog rise  11/26 06:27:34.50 R1+B   same file, press + 0.00 .. 1.30 s
  stretch   11/25 21:31:59.38 R2+A   factory-auto-20261125-195810-004.jsonl
            taps  press + 0.00 .. 0.38 s (only tau is used)
            body  press + 0.38 .. 4.60 s
  shake     11/25 21:32:15.90 R2+B   same file, press + 0.00 .. 4.60 s
  love      11/25 21:32:31.98 R2+Y   same file, press + 0.40 .. 6.10 s (after its own taps)
  greet     11/25 21:43:28.48 L1+A   same file, press + 0.40 .. 6.90 s (after its own taps)

Usage: gen_moves_dog_sit.py [trace_dir_1126] [trace_dir_1125] > include/foothold/moves_dog_sit.hpp
"""
import datetime
import json
import sys
from pathlib import Path

DIR_1126 = '/home/jay/data/overnight-1122/jetson-logs/dogsit-1126'
DIR_1125 = '/home/jay/data/overnight-1122/jetson-logs/trace-pull-1125'


def kst(day, h, m, s, us):
    tz = datetime.timezone(datetime.timedelta(hours=9))
    return datetime.datetime(2026, 11, day, h, m, s, us, tzinfo=tz).timestamp()


def segment(path, press, lo, hi):
    rows = []
    for line in open(path):
        try:
            r = json.loads(line)
        except json.JSONDecodeError:
            continue
        if 'q' in r and 'tau' in r and press + lo - 1e-3 <= r['wall'] <= press + hi + 1e-3:
            rows.append(r)
    if len(rows) < 5 or any(len(r[k]) != 12 for r in rows for k in ('q', 'dq', 'tau')):
        raise SystemExit(f'{path} {lo}..{hi}: bad segment')
    return rows


def emit(out, name, rows, note):
    t0 = rows[0]['wall']
    out += ['', f'// {note}, {len(rows)} rows.', f'inline constexpr std::array<MoveRow, {len(rows)}> {name}{{{{']
    for r in rows:
        f = lambda v: '{{' + ', '.join(f'{x:.4f}f' for x in v) + '}}'
        out.append(f"    {{{r['wall'] - t0:.3f}f, {f(r['q'])}, {f(r['dq'])}, {f(r['tau'])}}},")
    out.append('}};')


def main():
    d26 = Path(sys.argv[1] if len(sys.argv) > 1 else DIR_1126)
    d25 = Path(sys.argv[2] if len(sys.argv) > 2 else DIR_1125)
    f26 = d26 / 'factory-auto-20261126-062117-000.jsonl'
    f25 = d25 / 'factory-auto-20261125-195810-004.jsonl'
    sit, rise, stretch = kst(26, 6, 27, 27, 260000), kst(26, 6, 27, 34, 500000), kst(25, 21, 31, 59, 380000)
    out = [
        '// Generated by tools/gen_moves_dog_sit.py. Do not edit by hand.',
        '// Source: factory-mode traces of the real Go2 X (50 Hz, policy joint order, q dq tau).',
        '#pragma once',
        '',
        '#include "foothold/core.hpp"',
        '',
        'namespace foothold {',
        'struct MoveRow {',
        '    float t;',
        '    Joints q, dq, tau;',
        '};',
    ]
    emit(out, 'dog_taps', segment(f26, sit, 0.0, 0.46), 'dog sit taps 11/26 06:27:27 R1+B press + 0.00 .. 0.46 s')
    emit(out, 'dog_sit_down', segment(f26, sit, 0.46, 1.40), 'dog sit 11/26 06:27:27 R1+B press + 0.46 .. 1.40 s')
    emit(out, 'dog_rise', segment(f26, rise, 0.0, 1.30), 'dog rise 11/26 06:27:34 R1+B press + 0.00 .. 1.30 s')
    emit(out, 'stretch_taps', segment(f25, stretch, 0.0, 0.38), 'stretch taps 11/25 21:31:59 R2+A press + 0.00 .. 0.38 s')
    emit(out, 'stretch_body', segment(f25, stretch, 0.38, 4.60), 'stretch 11/25 21:31:59 R2+A press + 0.38 .. 4.60 s')
    shake, love, greet = kst(25, 21, 32, 15, 900000), kst(25, 21, 32, 31, 980000), kst(25, 21, 43, 28, 480000)
    emit(out, 'shake_body', segment(f25, shake, 0.0, 4.60), 'shake hands 11/25 21:32:15 R2+B press + 0.00 .. 4.60 s')
    emit(out, 'love_body', segment(f25, love, 0.40, 6.10), 'love 11/25 21:32:31 R2+Y press + 0.40 .. 6.10 s (stands on hind legs)')
    emit(out, 'greet_body', segment(f25, greet, 0.40, 6.90), 'greet 11/25 21:43:28 L1+A press + 0.40 .. 6.90 s (stands on hind legs)')
    for name, press, hi in (('stretch', stretch, 4.6), ('shake', shake, 4.6), ('love', love, 6.1), ('greet', greet, 6.9)):
        end = segment(f25, press, hi - 0.1, hi)[-1]
        sys.stderr.write(f"{name} end gz {end['grav'][2]:.2f} err {end['sport']['err']} thigh {[round(x, 2) for x in end['q'][4:8]]}\n")
    out += ['}', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
