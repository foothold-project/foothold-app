#!/usr/bin/env python3
"""Generate include/foothold/moves_dog_sit.hpp from the 11/25 factory joint recording.

Source: MOVES-1125.json (cut_moves_1125.py, 50 Hz LowState q recorded on the real Go2 X
while the factory controller ran Sit Down (R1+B) and stood back up (R1+B again)).
Joint order is the policy order: hip FL FR RL RR, thigh FL FR RL RR, calf FL FR RL RR.

The q_traj time axis starts at -1.0 s (1 s pad before the button press). Only the
motion segments are kept, at the original timing:
  sit_down       t = 0.98 .. 2.00 s  (file start + 1.98 .. 3.00 s): stand -> dog sit
  rise_from_sit  t = 0.82 .. 2.02 s  (file start + 1.82 .. 3.02 s): dog sit -> stand
Each segment is rebased so its first row is t = 0.

Usage: gen_moves_dog_sit.py [MOVES-1125.json] > include/foothold/moves_dog_sit.hpp
"""
import json
import sys

DEFAULT_SOURCE = '/home/jay/data/overnight-1122/jetson-logs/moves-1125/MOVES-1125.json'
SEGMENTS = [('dog_sit_down', 'sit_down', 0.98, 2.00), ('dog_rise', 'rise_from_sit', 0.82, 2.02)]


def main() -> None:
    source = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SOURCE
    moves = json.load(open(source))
    out = [
        '// Generated by tools/gen_moves_dog_sit.py. Do not edit by hand.',
        '// Source: MOVES-1125.json (factory Sit Down / stand again, real Go2 X, 50 Hz, policy joint order).',
        '#pragma once',
        '',
        '#include "foothold/core.hpp"',
        '',
        'namespace foothold {',
        'struct MoveFrame {',
        '    float t;',
        '    Joints q;',
        '};',
    ]
    for name, key, lo, hi in SEGMENTS:
        rows = [r for r in moves[key]['q_traj'] if lo <= r[0] <= hi]
        if len(rows) < 2 or any(len(r) != 13 for r in rows):
            raise SystemExit(f'{key}: bad segment')
        t0 = rows[0][0]
        out += ['', f'// {key} q_traj t = {lo:.2f} .. {hi:.2f} s, {len(rows)} rows.',
                f'inline constexpr std::array<MoveFrame, {len(rows)}> {name}{{{{']
        for r in rows:
            q = ', '.join(f'{x:.4f}f' for x in r[1:])
            out.append(f'    {{{r[0] - t0:.3f}f, {{{{{q}}}}}}},')
        out.append('}};')
    out += ['}', '']
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
